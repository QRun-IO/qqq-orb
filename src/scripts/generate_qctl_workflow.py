"""Canonical native-platform exception: emit a tiny qctl reusable-workflow caller."""
import os
import re
import sys
import argparse
from pathlib import Path


def generate(shared_ref):
    if not re.fullmatch(r'[0-9a-f]{40}', shared_ref):
        raise ValueError('shared_ref must be the reviewed immutable QRun-IO/qqq-orb commit SHA')
    return '''# Generated by qqq-orb generate_qctl_workflow; edit the central worker, not local jobs.
# GitHub-native macOS/Windows runners are required for the release binaries.
name: Build
on:
  push:
    branches: [main, develop]
    tags: ['v*']
  pull_request:
    branches: [main, develop]
  workflow_dispatch:
    inputs:
      full_native:
        description: Qualify all five native platforms without publishing
        type: boolean
        default: false
permissions:
  contents: write
  packages: write
  pull-requests: write
jobs:
  native:
    uses: QRun-IO/qqq-orb/.github/workflows/qctl-native.yml@''' + shared_ref + '''
    with:
      full_native: ${{ github.event_name == 'workflow_dispatch' && inputs.full_native }}
    secrets: inherit
'''


if __name__ == '__main__':
    try:
        parser = argparse.ArgumentParser()
        parser.add_argument('--check', type=Path, help='Fail unless an existing caller is canonical')
        args = parser.parse_args()
        rendered = generate(os.environ['QCTL_SHARED_REF'])
        if args.check:
            if args.check.read_text() != rendered:
                raise ValueError('qctl caller differs from canonical orb-generated definition')
            print('qctl caller is canonical')
        else:
            print(rendered, end='')
    except (KeyError, ValueError) as error:
        sys.exit(str(error))
